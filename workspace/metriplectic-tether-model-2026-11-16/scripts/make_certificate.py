"""Write CERTIFICATE.md from the outputs produced by ./verify.sh (nothing is hand-entered)."""
import hashlib, subprocess, sys
commit, mathlib_rev, man_sha, tc_sha, archive, stamp = sys.argv[1:7]
O = "certificates"
def sh(cmd): return subprocess.run(cmd, shell=True, capture_output=True, text=True).stdout.strip()
def sha(p): return hashlib.sha256(open(p, "rb").read()).hexdigest()
def rd(p): return open(p, encoding="utf-8").read().rstrip("\n")
pdf = "paper/metriplectic_tether_model.pdf"; tex = "paper/metriplectic_tether_model.tex"
lines = [
 "# Kernel certificate: MetriplecticTetherModel",
 "",
 "Copyright (c) 2026 Benjamin Stanley Frohman. Author: Benjamin Stanley Frohman",
 "",
 "Generated by `./verify.sh` (script `scripts/make_certificate.py`) from the actual `lake build`,",
 "`#print axioms` and `leanchecker` runs below. No value in this file is hand-written.",
 "",
 "| Item | Value |", "|---|---|",
 f"| Generated | {stamp} |",
 f"| Repository commit (HEAD at build) | `{commit}` |",
 f"| Last commit touching the Lean sources, lakefile, manifest or toolchain (cited in the paper) | `{sh('git log -1 --format=%H -- MetriplecticTetherModel MetriplecticTetherModel.lean lakefile.lean lake-manifest.json lean-toolchain scripts/PrintAxioms.lean')}` |",
 f"| `lean-toolchain` contents | `{open('lean-toolchain').read().strip()}` |",
 f"| sha256 `lean-toolchain` | `{tc_sha}` |",
 f"| sha256 `lake-manifest.json` | `{man_sha}` |",
 f"| Mathlib rev (from manifest) | `{mathlib_rev}` |",
 f"| elan | `{sh('elan --version')}` |",
 f"| lake | `{sh('lake --version')}` |",
 f"| lean | `{sh('lake env lean --version')}` |",
 f"| Pin source | byte-for-byte copies of `BenFrohman/frohmanian-symplectic-tether-regularity` @ `2a649d1d2671d9059af47c4cfaf9748b82d71a5b` |",
 f"| sha256 paper PDF `{pdf}` | `{sha(pdf)}` |",
 f"| sha256 paper source `{tex}` | `{sha(tex)}` |",
 f"| sha256 locked claim source `paper/main_theorem.tex` | `{sha('paper/main_theorem.tex')}` |",
 f"| Source archive `certificates/{archive}` (`git archive` of HEAD) | sha256 `{sha(O + '/' + archive)}` |",
 "| Rebuild command | `./verify.sh` |",
 "",
 "## Summary", "",
 "```", rd(O + "/axioms-summary.txt"), rd(O + "/source-scan.txt").splitlines()[-1],
 [l for l in rd(O + "/truth-gate.txt").splitlines() if l.startswith("TRUTH GATE")][0],
 f"leanchecker: {rd(O + '/leanchecker.txt').count(': OK')} modules replayed OK, {rd(O + '/leanchecker.txt').count(': FAIL')} failures",
 "```", "",
 "## Truth Gate (semantics lock)", "", "```", rd(O + "/truth-gate.txt"), "```", "",
 "## Source scan (header + forbidden tokens)", "", "```", rd(O + "/source-scan.txt"), "```", "",
 "## `#print axioms` output (`lake env lean scripts/PrintAxioms.lean`)", "", "```", rd(O + "/axioms.txt"), "```", "",
 "## Kernel replay (`leanchecker --verbose`, per module)", "", "```", rd(O + "/leanchecker.txt"), "```", "",
 "## Full `lake build -v` log", "", "```", rd(O + "/build.log"), "```", "",
]
open("CERTIFICATE.md", "w", encoding="utf-8").write("\n".join(lines) + "\n")
